"""
How wrong is the ring tracker (onboard/obs.RingTracker) while the ring is out of view?

    python hardware/privileged/tracker_accuracy.py                  # 20 teacher lap episodes
    python hardware/privileged/tracker_accuracy.py --episodes 40 --profile typical

The privileged teacher flies same-side laps (so the ring really does go out of view on the way
round); every tick the tracker's estimate is compared with the true ring centre in the drone's body
frame (forward, right, up) from the simulator. Errors are grouped by how long the drone has been
blind (time since the last fresh detection). Writes hardware/privileged/reports/tracker_accuracy.md.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
HW = HERE.parent
if str(HW) not in sys.path:
    sys.path.insert(0, str(HW))

from onboard import spec  # noqa: E402
from onboard.gym_env import OnboardHoopEnv  # noqa: E402
from privileged.gates import LAPS  # noqa: E402
from privileged.teacher import PrivilegedTeacher  # noqa: E402

BINS = [(0.0, 0.01, "seen this tick"), (0.01, 0.5, "blind < 0.5 s"), (0.5, 1.0, "0.5-1 s"),
        (1.0, 2.0, "1-2 s"), (2.0, 3.0, "2-3 s"), (3.0, 99.0, "> 3 s")]


def true_body(sim):
    d = np.asarray(sim.ring.centre, float) - np.asarray(sim.pos, float)
    return np.array([float(np.dot(d, sim.forward)), float(np.dot(d, sim.right)), float(d[2])])


def measure(episodes, profile, seed=4000):
    env = OnboardHoopEnv(seed=seed, profile=profile, ring_tracker=True, **LAPS)
    teacher = PrivilegedTeacher()
    rows = []                                   # (blind seconds, error vector, true distance)
    for ep in range(episodes):
        env.reset(seed=seed + ep)
        blind = 0.0
        while True:
            obs, _, term, trunc, _ = env.step(teacher(env))
            tr = env.builder.tracker
            fresh = obs[spec.OBS_SLICES["age"].start] <= 1e-6
            blind = 0.0 if fresh else blind + spec.CTRL_DT
            if tr.valid:
                truth = true_body(env.sim)
                rows.append((blind, tr.p - truth, float(np.linalg.norm(truth))))
            if term or trunc:
                break
    return rows


def table(rows):
    L = ["| Blind for | Ticks | Median error | 90th pct | Median fwd / right / up error (signed) |",
         "|---|---|---|---|---|"]
    for lo, hi, name in BINS:
        sel = [r for r in rows if lo <= r[0] < hi]
        if not sel:
            continue
        e = np.array([r[1] for r in sel])
        n = np.linalg.norm(e, axis=1)
        med = np.median(e, axis=0)
        L.append(f"| {name} | {len(sel)} | {np.median(n):.2f} m | {np.percentile(n, 90):.2f} m | "
                 f"{med[0]:+.2f} / {med[1]:+.2f} / {med[2]:+.2f} m |")
    return L


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--episodes", type=int, default=20)
    ap.add_argument("--profile", default="measured")
    ap.add_argument("--out", type=Path, default=HERE / "reports" / "tracker_accuracy.md")
    a = ap.parse_args(argv)
    rows = measure(a.episodes, a.profile)
    blind = [r for r in rows if r[0] > 0]
    L = ["# Ring tracker accuracy", "",
         f"The privileged teacher flew {a.episodes} same-side lap episodes ({a.profile} profile, dr 1). Every tick, "
         "the tracker's estimate of the ring centre (body frame) vs the simulator's truth. "
         f"{len(blind)} of {len(rows)} ticks were blind (ring not freshly detected). "
         "Generated by `hardware/privileged/tracker_accuracy.py`.", ""] + table(rows) + [
         "", "\"Seen this tick\" is the camera's own error (range from apparent size, bearing from the image "
         "centre). Blind rows show how the dead reckoning drifts: turning is measured (telemetry yaw), "
         "forward and sideways motion is assumed from the commands at the nominal speed.", ""]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
