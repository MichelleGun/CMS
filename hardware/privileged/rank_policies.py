"""
Which policy should fly? Scores policies on THE GOAL (enter the hoop, loop round, re-enter, as many
times as possible) in the corrected simulator, so the choice is made by numbers.

    python hardware/privileged/rank_policies.py                         # newest 12 onboard runs
    python hardware/privileged/rank_policies.py results/hoop/runs/w10_front_B_gamma results/hoop/runs/onboard_20261011-032612
    python hardware/privileged/rank_policies.py --episodes 36           # tighter numbers, slower

Per policy (best_model.zip, loaded exactly as fly_hoop.py loads it, old yaw convention converted):
laps per 90 s on same-side laps from all 9 start zones, clean episodes (>= 2 laps, no crash), best
streak, and front-runway single-pass rate. Measured profile, dr 1, the training ring, the same
layouts for every policy. The privileged teacher is the first row: the ceiling, not a candidate
(it reads the simulator's true state, which no real flight has).
Writes hardware/privileged/reports/policy_ranking.md, best laps per 90 s first.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
HW = HERE.parent
CMS = HW.parent
if str(HW) not in sys.path:
    sys.path.insert(0, str(HW))

from onboard import spec  # noqa: E402
from onboard.policy import load_policy  # noqa: E402
from privileged.gates import FRONT, LAPS, MEASURED, run  # noqa: E402
from privileged.teacher import PrivilegedTeacher  # noqa: E402

RUNS = CMS / "results" / "hoop" / "runs"


def candidates(paths, limit):
    if paths:
        out = []
        for p in map(Path, paths):
            z = p if p.suffix == ".zip" else p / "best_model.zip"
            if z.exists():
                out.append(z)
            else:
                print(f"[SKIP] no model at {z}")
        return out
    found = []
    for d in RUNS.iterdir():
        z = d / "best_model.zip"
        try:
            meta = json.loads((d / "meta.json").read_text())
        except (OSError, ValueError):
            continue
        if z.exists() and meta.get("task") == spec.TASK_NAME:
            found.append((z.stat().st_mtime, z))
    return [z for _, z in sorted(found, reverse=True)[:limit]]


def score(controller, episodes):
    lp = run(controller, LAPS, MEASURED, episodes, seed=7000)
    good = [p >= 2 and o not in ("struck", "out_of_cage") for p, o in zip(lp["passes"], lp["outcomes"])]
    fr = run(controller, FRONT, MEASURED, max(10, episodes), seed=8000)
    return dict(laps=float(np.mean(lp["passes"])), clean=float(np.mean(good)), best=int(max(lp["passes"])),
                front=float(np.mean([o == "passed" for o in fr["outcomes"]])),
                crashes=sum(o in ("struck", "out_of_cage") for o in lp["outcomes"]))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("models", nargs="*", help="run folders or .zip files (default: newest onboard runs)")
    ap.add_argument("--episodes", type=int, default=18, help="lap episodes per policy (9 zones x 2)")
    ap.add_argument("--limit", type=int, default=12)
    ap.add_argument("--out", type=Path, default=HERE / "reports" / "policy_ranking.md")
    a = ap.parse_args(argv)

    rows = []
    t = score(lambda env, obs: PrivilegedTeacher()(env), a.episodes)
    print(f"[RANK] teacher (ceiling): laps/90s {t['laps']:.2f}", flush=True)
    for z in candidates(a.models, a.limit):
        try:
            fn = load_policy(z)
        except (ValueError, FileNotFoundError) as e:
            print(f"[SKIP] {z.parent.name}: {e}")
            continue
        s = score(lambda env, obs, f=fn: f(obs), a.episodes)
        s.update(name=z.parent.name, path=str(z.relative_to(CMS)) if CMS in z.parents else str(z),
                 converted=bool(getattr(fn, "yaw_converted", False)))
        rows.append(s)
        print(f"[RANK] {s['name']:34s} laps/90s {s['laps']:.2f}  clean {s['clean']:.0%}  best {s['best']}  "
              f"front {s['front']:.0%}", flush=True)
    rows.sort(key=lambda r: (r["laps"], r["front"]), reverse=True)
    L = ["# Which policy should fly?", "",
         "Goal: enter the hoop, loop round the outside, re-enter, as many times as possible. Corrected simulator "
         f"(measured profile, dr 1, training ring), {a.episodes} lap episodes of 90 s from all 9 start zones per "
         "policy, same layouts for all. Generated by `hardware/privileged/rank_policies.py`.", "",
         "| # | Policy | Laps / 90 s | Clean (≥2, no crash) | Best streak | Crashes | Front-runway pass | Model |",
         "|---|---|---|---|---|---|---|---|",
         f"| – | *privileged teacher (ceiling, sees the true state)* | {t['laps']:.2f} | {t['clean']:.0%} | {t['best']} | "
         f"{t['crashes']} | {t['front']:.0%} | – |"]
    for i, r in enumerate(rows, 1):
        L.append(f"| {i} | {r['name']}{' (yaw-converted)' if r['converted'] else ''} | **{r['laps']:.2f}** | "
                 f"{r['clean']:.0%} | {r['best']} | {r['crashes']} | {r['front']:.0%} | `{r['path']}` |")
    L += ["", "To fly the top one: yaw hand check first (turn the drone clockwise on the floor: `yaw` must go up), "
          "then `python hardware/onboard/fly_hoop.py --mode policy --model <Model> --dry-run`, then the same "
          "without `--dry-run`.", ""]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(L), encoding="utf-8")
    print(f"[DONE] {a.out}")
    return rows


if __name__ == "__main__":
    main()
